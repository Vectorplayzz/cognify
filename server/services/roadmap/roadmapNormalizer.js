/**
 * Roadmap Normalizer — parsed upstream data -> Cognify's roadmap schema.
 *
 * Cognify renders ordered levels (types.ts: RoadmapLevel), each with
 * subtopics and a lazily generated quiz. Source-specific fields are kept
 * under `source` rather than mixed into Cognify's own fields.
 */

// Matches the XP curve the AI generator already used: 100, then +50 a level.
const BASE_XP = 100;
const XP_STEP = 50;

export function xpForLevel(order) {
    return BASE_XP + (order - 1) * XP_STEP;
}

/** First sentence(s) of a body, for the level/subtopic summary line. */
function summarize(text, max = 280) {
    if (!text) return '';
    const plain = text
        .replace(/```[\s\S]*?```/g, ' ')
        .replace(/[#>*_`]/g, '')
        .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
        .replace(/\s+/g, ' ')
        .trim();
    if (plain.length <= max) return plain;
    const cut = plain.slice(0, max);
    const stop = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('! '), cut.lastIndexOf('? '));
    return (stop > 80 ? cut.slice(0, stop + 1) : cut).trim();
}

/**
 * Build a Cognify roadmap from parsed upstream topics.
 *
 * @param parsed   output of parseRoadmapGraph
 * @param contents Map<nodeId, { heading, body }>
 */
export function normalizeRoadmap({ parsed, contents, slug, topicQuery }) {
    const levels = parsed.topics.map((topic) => {
        const own = contents.get(topic.id) || { heading: '', body: '' };

        const subtopics = topic.subtopics.map((sub) => {
            const c = contents.get(sub.id) || { heading: '', body: '' };
            return {
                id: sub.id,
                title: sub.title || c.heading || 'Untitled',
                description: summarize(c.body, 200),
                content: c.body || '',
                source: { nodeId: sub.id },
            };
        });

        // A topic with no prose of its own still reads well if we lead with
        // what its subtopics cover.
        const description =
            summarize(own.body, 280) ||
            (subtopics.length
                ? `Covers ${subtopics.slice(0, 4).map((s) => s.title).join(', ')}${subtopics.length > 4 ? ' and more' : ''}.`
                : `Learn about ${topic.title}.`);

        return {
            id: topic.id,
            order: topic.order,
            title: topic.title,
            description,
            theoryContent: own.body || '',
            subtopics,
            imageQuery: `${topic.title} ${topicQuery || slug}`.trim(),
            xpReward: xpForLevel(topic.order),
            // Quizzes stay lazily generated by the existing /level-quiz flow.
            quiz: [],
            source: { nodeId: topic.id },
        };
    });

    return {
        source: 'roadmap.sh',
        sourceSlug: slug,
        sourceUrl: `https://roadmap.sh/${slug}`,
        title: parsed.title || slug,
        description: parsed.description || '',
        levels,
    };
}

/**
 * Shape an AI-generated roadmap the same way, so the frontend cannot tell
 * the two apart beyond the `source` field.
 */
export function normalizeAiRoadmap({ levels, topic, provider }) {
    return {
        source: 'ai',
        sourceProvider: provider,
        title: `${topic} Roadmap`,
        description: '',
        levels: levels.map((l, i) => ({
            id: `ai-${i + 1}`,
            order: i + 1,
            title: l.title,
            description: l.description || '',
            theoryContent: '',
            subtopics: [],
            imageQuery: `${l.title} ${topic}`.trim(),
            xpReward: Number(l.xpReward) || xpForLevel(i + 1),
            quiz: [],
        })),
    };
}
